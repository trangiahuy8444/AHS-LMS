/**
 * Lấy danh sách học sinh theo lớp (sắp xếp theo STT)
 */
export function getStudentsByClass(className) {
  if (!className) return [];
  const list = ROSTER_BY_CLASS[className] || [];
  return [...list].sort((a, b) => a.stt - b.stt);
}

/**
 * Chuẩn hóa mã LMS để đối soát (bỏ dấu gạch ngang, khoảng trắng, chuyển chữ thường)
 */
export function cleanLmsCode(val) {
  return String(val || "")
    .normalize("NFKC")
    .replace(/[\u2010-\u2015\u2212]/g, "-")
    .replace(/[^a-zA-Z0-9]/g, "")
    .toLowerCase()
    .trim();
}

/**
 * Đối soát xem Mã LMS nhập vào có khớp với học sinh đã chọn hay không.
 * QUY ĐỊNH BẮT BUỘC: Nhập đầy đủ toàn bộ mã, KHÔNG chấp nhận chỉ nhập 4 số cuối.
 * 
 * Hỗ trợ đối soát linh hoạt giữa các cột dữ liệu trường:
 * 1. Mã số thuần (VD: "01190002", "14190055")
 * 2. Mã có dấu gạch ngang (VD: "01-19-0002", "14-19-0055")
 * 3. Cột SIS ID (Đối sánh khi ID đăng nhập thiếu hoặc không khớp)
 * 4. Mã đầy đủ khi bị rớt số 0 đầu (VD: "1190002", "1-19-0002")
 * 5. Mã Canvas User ID (VD: "24999", "25000", "20992")
 * 6. Tài khoản Email (cho các trường hợp học sinh đăng nhập bằng Gmail cá nhân)
 */
export function verifyStudentLms(student, inputLms) {
  if (!student || !inputLms) return false;
  const rawInput = String(inputLms).trim();
  const cleanInput = cleanLmsCode(rawInput);
  if (!cleanInput) return false;

  const stdLms = cleanLmsCode(student.studentId);
  const stdLogin = cleanLmsCode(student.loginId);
  const stdSis = cleanLmsCode(student.sisId);
  const stdCanvas = student.canvasUserId ? cleanLmsCode(student.canvasUserId) : "";
  const stdLegacy = student.legacyId ? cleanLmsCode(student.legacyId) : "";

  // 1. Khớp chính xác toàn bộ mã (chuỗi đầy đủ không dấu gạch ngang)
  if (stdLms && cleanInput === stdLms) return true;
  if (stdLogin && cleanInput === stdLogin) return true;
  if (stdSis && cleanInput === stdSis) return true;
  if (stdCanvas && cleanInput === stdCanvas) return true;
  if (stdLegacy && cleanInput === stdLegacy) return true;

  // 2. Khớp mã đầy đủ khi bị rớt số 0 ở đầu (độ dài mã đầy đủ >= 6 ký tự)
  const stripZeros = (s) => String(s || "").replace(/^0+/, "");
  if (cleanInput.length >= 6) {
    if (stdLms && stripZeros(cleanInput) === stripZeros(stdLms)) return true;
    if (stdLogin && stripZeros(cleanInput) === stripZeros(stdLogin)) return true;
    if (stdSis && stripZeros(cleanInput) === stripZeros(stdSis)) return true;
  }

  // 3. Khớp theo email (nếu tài khoản là email cá nhân: khớp email hoặc username trước @)
  if (student.loginId && student.loginId.includes("@")) {
    const emailUser = cleanLmsCode(student.loginId.split("@")[0]);
    if (cleanInput === emailUser || cleanInput === cleanLmsCode(student.loginId)) return true;
    const emailNum = student.studentId ? cleanLmsCode(student.studentId) : "";
    if (emailNum && cleanInput === emailNum) return true;
  }

  // TỪ CHỐI nếu chỉ nhập 4 số cuối hoặc mã rút gọn (Quy định: Bắt buộc nhập đầy đủ)
  return false;
}

/**
 * Tìm học sinh trong lớp theo Mã LMS (dùng cho Auto-Fill khi học sinh gõ toàn bộ mã trước)
 */
export function findStudentInClassByLms(className, inputLms) {
  const students = getStudentsByClass(className);
  if (!students.length || !inputLms) return null;
  return students.find(s => verifyStudentLms(s, inputLms)) || null;
}

/**
 * Tìm học sinh trong toàn bộ Khối theo Mã LMS
 */
export function findStudentInGradeByLms(grade, inputLms) {
  const clean = cleanLmsCode(inputLms);
  if (!clean) return null;
  for (const [cls, list] of Object.entries(ROSTER_BY_CLASS)) {
    if (cls.startsWith(String(grade) + "/")) {
      const match = list.find(s => verifyStudentLms(s, clean));
      if (match) return { ...match, studentClass: cls, grade: Number(grade) };
    }
  }
  return null;
}
